const messages: Record<Language, LocaleMessages> = {
  'zh-CN': zhCN,
  'zh-TW': zhTW,
  'en-US': enUS,
};

export const getMessages = (language: Language): LocaleMessages => {
  return messages[language] || messages['zh-CN'];
};

export const t = (key: string, language: Language = 'zh-CN'): string => {
  const keys = key.split('.');
  let result: any = getMessages(language);
  
  for (const k of keys) {
    if (result && typeof result === 'object' && k in result) {
      result = result[k];
    } else {
      return key;
    }
  }
  
  return typeof result === 'string' ? result : key;
};

